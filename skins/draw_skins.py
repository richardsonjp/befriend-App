#!/usr/bin/env python3
"""Draws the pixel-cat and pixel-dog skin sources (text grids for backend/pkg/skinpack) and preview sheets.

skins/pixel-cat and skins/pixel-dog are generated by this script and rewritten on every run: change the drawing
here, not the grids. Afterwards rebuild PetCore's pixel-cat.zip (see skins/README.md).

Body parts are filled pixel shapes; drawing a part outlines it (every 4-neighbour pixel outside the part turns
dark), back to front, so front parts get crisp edges over what's behind them. Faces and minis are hand-written.

usage: python3 skins/draw_skins.py skins <preview dir>
"""
import json
